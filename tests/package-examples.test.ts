/**
 * Every `packages/<pkg>/examples/*.ts` compiles and runs with
 * `typesugar run examples/<file>.ts` -- the command the showcases' headers
 * give -- through the BUILT CLI (`packages/transformer/dist/cli.js`), from the
 * package directory, so `@typesugar/*` imports resolve as they do there.
 *
 * Nothing ran these files, so they rotted: std's showcase had a failed
 * typeAssert, a non-exhaustive match and three run-time "is not a function"s
 * (round-2 docs findings). Each example is one test, run one at a time (~1 s
 * and ~350 MB each).
 *
 * KNOWN_BROKEN lists the examples that fail today, with why. They run as
 * `it.fails`, so the suite stays green while they are broken, and a fix shows
 * up as a failure saying to take the file off the list. A NEW failure in any
 * other example fails the suite.
 *
 * `typesugar run` does not type-check (it transpiles), so an example could
 * "run" with type errors and drift from the API unnoticed: the transformer
 * showcase ran with 7. Each example is therefore also type-checked with
 * `typesugar check` (macro diagnostics plus the TypeScript errors left after
 * typesugar's suppression rules, as in the IDE), against a generated
 * tsconfig that extends the package's own and lists just that file
 * (written under the package's gitignored `.typesugar/`). ~0.6 s each.
 * KNOWN_TYPE_ERRORS works like KNOWN_BROKEN.
 */

import { describe, it, expect } from "vitest";
import { spawnSync } from "child_process";
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cliPath = path.join(repoRoot, "packages", "transformer", "dist", "cli.js");
const hasBuild = fs.existsSync(cliPath);

const KNOWN_BROKEN: Record<string, string> = {};

const KNOWN_TYPE_ERRORS: Record<string, string> = {
  "packages/effect/examples/effect-adapter-example.ts":
    "an arrow-body `let:` comprehension is a syntax error outside the pipeline: " +
    "`typesugar check`/`build` (and ts-patch tsc) never run the expression-comprehension preprocessor",
  "packages/sql/examples/doobie-style-example.ts":
    "`UserMeta` is generated by @derive(Meta), so TypeScript reports TS2304 for it before expansion",
};

function examples(): string[] {
  const out: string[] = [];
  for (const pkg of fs.readdirSync(path.join(repoRoot, "packages")).sort()) {
    const dir = path.join(repoRoot, "packages", pkg, "examples");
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (f.endsWith(".ts") && !f.endsWith(".d.ts")) out.push(`packages/${pkg}/examples/${f}`);
    }
  }
  return out;
}

/**
 * `typesugar check` on one example: a tsconfig extending the package's own
 * (or the repo base when the package has none), with the example as its only
 * file. `rootDir` is the package (the example is outside `src`), and
 * declaration output is off (nothing is emitted).
 */
function checkExample(rel: string): { status: number | null; output: string } {
  const pkgDir = path.join(repoRoot, path.dirname(path.dirname(rel)));
  const cfgDir = path.join(pkgDir, ".typesugar", "examples-check");
  fs.mkdirSync(cfgDir, { recursive: true });
  const file = path.basename(rel);
  const cfg = path.join(cfgDir, file.replace(/\.ts$/, ".tsconfig.json"));
  const base = fs.existsSync(path.join(pkgDir, "tsconfig.json"))
    ? "../../tsconfig.json"
    : path.relative(cfgDir, path.join(repoRoot, "tsconfig.base.json"));
  fs.writeFileSync(
    cfg,
    JSON.stringify({
      extends: base,
      compilerOptions: {
        noEmit: true,
        rootDir: "../..",
        composite: false,
        declaration: false,
        declarationMap: false,
        incremental: false,
      },
      files: [`../../examples/${file}`],
      include: [],
    })
  );
  const r = spawnSync(process.execPath, [cliPath, "check", "--project", cfg], {
    cwd: pkgDir,
    encoding: "utf-8",
    stdio: ["ignore", "pipe", "pipe"],
    timeout: 120_000,
  });
  return { status: r.status, output: (r.stdout ?? "") + (r.stderr ?? "") };
}

function runExample(rel: string): { status: number | null; output: string } {
  const pkgDir = path.join(repoRoot, path.dirname(path.dirname(rel)));
  const r = spawnSync(
    process.execPath,
    [cliPath, "run", path.join("examples", path.basename(rel))],
    {
      cwd: pkgDir,
      encoding: "utf-8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 120_000,
    }
  );
  return { status: r.status, output: (r.stdout ?? "") + (r.stderr ?? "") };
}

describe.skipIf(!hasBuild)("package examples run with `typesugar run`", () => {
  const all = examples();

  it("every KNOWN_BROKEN / KNOWN_TYPE_ERRORS entry is an existing example", () => {
    expect(Object.keys(KNOWN_BROKEN).filter((f) => !all.includes(f))).toEqual([]);
    expect(Object.keys(KNOWN_TYPE_ERRORS).filter((f) => !all.includes(f))).toEqual([]);
  });

  for (const rel of all) {
    const reason = KNOWN_BROKEN[rel];
    if (reason) {
      // Known broken (reason in KNOWN_BROKEN), tracked on PR #83: expected to
      // fail until fixed, then this flips to a failure and the entry goes.
      it.fails(
        `${rel} (known broken: ${reason}; remove it from KNOWN_BROKEN once it runs)`,
        () => {
          const { status, output } = runExample(rel);
          expect(status, output.slice(-3000)).toBe(0);
        },
        120_000
      );
    } else {
      it(
        rel,
        () => {
          const { status, output } = runExample(rel);
          expect(status, output.slice(-3000)).toBe(0);
        },
        120_000
      );
    }
  }

  for (const rel of all) {
    const reason = KNOWN_TYPE_ERRORS[rel];
    const name = `${rel} type-checks with \`typesugar check\``;
    if (reason) {
      // Known type errors (reason in KNOWN_TYPE_ERRORS), tracked on PR #83.
      it.fails(
        `${name} (known: ${reason}; remove it from KNOWN_TYPE_ERRORS once it checks)`,
        () => {
          const { status, output } = checkExample(rel);
          expect(status, output.slice(-3000)).toBe(0);
        },
        120_000
      );
    } else {
      it(
        name,
        () => {
          const { status, output } = checkExample(rel);
          expect(status, output.slice(-3000)).toBe(0);
        },
        120_000
      );
    }
  }
});
