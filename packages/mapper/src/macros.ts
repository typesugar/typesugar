import * as ts from "typescript";
import {
  defineExpressionMacro,
  globalRegistry,
  isSyntheticNode,
  MacroContext,
} from "@typesugar/core";

export const transformIntoMacro = defineExpressionMacro({
  name: "transformInto",
  module: "@typesugar/mapper",
  description: "Zero-cost compile-time object mapping",

  expand(
    ctx: MacroContext,
    callExpr: ts.CallExpression,
    args: readonly ts.Expression[]
  ): ts.Expression {
    if (args.length < 1) {
      ctx.reportError(callExpr, "transformInto expects at least 1 argument");
      return callExpr;
    }

    const sourceExpr = args[0];
    const configExpr = args[1];

    // The types come from the checker, which cannot answer for macro-generated
    // (synthetic) nodes. Leave the call alone and say so, rather than throw.
    if (isSyntheticNode(callExpr) || isSyntheticNode(sourceExpr)) {
      ctx.reportWarning(
        callExpr,
        "transformInto was not expanded: the call was generated by another macro, so its types cannot be resolved. The runtime stub will throw if this call is reached."
      );
      return callExpr;
    }

    // 1. Get From and To types
    const fromType = ctx.getTypeOf(sourceExpr);
    // The return type of transformInto<From, To> is To
    const toType = ctx.getTypeOf(callExpr);

    // 2. Parse config
    const config = parseConfig(ctx, configExpr, "transformInto");

    // 3. Build the object literal mapping expression
    return buildMappingExpression(ctx, callExpr, sourceExpr, fromType, toType, config);
  },
});

export const transformArrayIntoMacro = defineExpressionMacro({
  name: "transformArrayInto",
  module: "@typesugar/mapper",
  description: "Zero-cost compile-time array mapping",

  expand(
    ctx: MacroContext,
    callExpr: ts.CallExpression,
    args: readonly ts.Expression[]
  ): ts.Expression {
    if (args.length < 1) {
      ctx.reportError(callExpr, "transformArrayInto expects at least 1 argument");
      return callExpr;
    }

    const itemsExpr = args[0];
    const configExpr = args[1];

    if (isSyntheticNode(callExpr) || isSyntheticNode(itemsExpr)) {
      ctx.reportWarning(
        callExpr,
        "transformArrayInto was not expanded: the call was generated by another macro, so its types cannot be resolved. The runtime stub will throw if this call is reached."
      );
      return callExpr;
    }

    // Parse config for element-level mapping
    const config = parseConfig(ctx, configExpr, "transformArrayInto");

    // Get the return type: To[] — we need the element type To
    const returnType = ctx.getTypeOf(callExpr);
    // Get the element type of the source array
    const itemsType = ctx.getTypeOf(itemsExpr);

    // Extract element types from array types
    const fromElementType = getArrayElementType(ctx, itemsType);
    const toElementType = getArrayElementType(ctx, returnType);

    if (!fromElementType || !toElementType) {
      ctx.reportError(callExpr, "transformArrayInto: could not resolve array element types");
      return callExpr;
    }

    // Generate: items.map((__item) => ({ ... }))
    // `items` stays in the caller's scope, so `await`/`yield` in it keep working.
    const itemParam = ctx.generateUniqueName("item");
    const mappingExpr = buildObjectLiteral(
      ctx,
      callExpr,
      itemParam,
      fromElementType,
      toElementType,
      config,
      ""
    );

    return ctx.factory.createCallExpression(
      ctx.factory.createPropertyAccessExpression(itemsExpr, "map"),
      undefined,
      [createArrow(ctx, itemParam, mappingExpr)]
    );
  },
});

/** `(param) => body` */
function createArrow(
  ctx: MacroContext,
  param: ts.Identifier,
  body: ts.ConciseBody
): ts.ArrowFunction {
  return ctx.factory.createArrowFunction(
    undefined,
    undefined,
    [ctx.factory.createParameterDeclaration(undefined, undefined, param)],
    undefined,
    ctx.factory.createToken(ts.SyntaxKind.EqualsGreaterThanToken),
    body
  );
}

/**
 * Build the full mapping expression for an object, handling temp vars if needed.
 */
function buildMappingExpression(
  ctx: MacroContext,
  callExpr: ts.CallExpression,
  sourceExpr: ts.Expression,
  fromType: ts.Type,
  toType: ts.Type,
  config: ParsedConfig
): ts.Expression {
  // Simple sources can be read repeatedly; anything else is bound once.
  if (ts.isIdentifier(sourceExpr) || isSimpleLiteral(sourceExpr)) {
    return buildObjectLiteral(ctx, callExpr, sourceExpr, fromType, toType, config, "");
  }

  // Bind the source by passing it as the ARGUMENT of an arrow, not by declaring
  // it inside the arrow's body: `((src) => ({ ... }))(<expr>)`. The argument is
  // evaluated in the caller's scope, so an `await` or `yield` in <expr> keeps
  // its meaning (FMG-4); inside a non-async arrow body it would be a SyntaxError.
  const tempName = ctx.generateUniqueName("src");
  const objLit = buildObjectLiteral(ctx, callExpr, tempName, fromType, toType, config, "");
  return ctx.factory.createCallExpression(
    ctx.factory.createParenthesizedExpression(
      createArrow(ctx, tempName, ctx.factory.createParenthesizedExpression(objLit))
    ),
    undefined,
    [sourceExpr]
  );
}

function isOptionalSymbol(sym: ts.Symbol): boolean {
  return (sym.flags & ts.SymbolFlags.Optional) !== 0;
}

/** The field's type with `null`/`undefined` removed, and whether anything was removed. */
function fieldType(ctx: MacroContext, sym: ts.Symbol): { type: ts.Type; nullable: boolean } {
  const full = ctx.typeChecker.getTypeOfSymbol(sym);
  const nonNull = ctx.typeChecker.getNonNullableType(full);
  return { type: nonNull, nullable: isOptionalSymbol(sym) || nonNull !== full };
}

function label(prefix: string, name: string): string {
  return prefix ? `${prefix}.${name}` : name;
}

/**
 * Report an error when a source field cannot be stored in a target field
 * (FMG-2). Returns true when the mapping is acceptable.
 */
function checkFieldAssignable(
  ctx: MacroContext,
  reportNode: ts.Node,
  targetLabel: string,
  sourceLabel: string,
  fromSym: ts.Symbol,
  toSym: ts.Symbol
): boolean {
  if (isOptionalSymbol(fromSym) && !isOptionalSymbol(toSym)) {
    ctx.reportError(
      reportNode,
      `Cannot map field '${targetLabel}': source field '${sourceLabel}' is optional but the target field is required.`
    );
    return false;
  }
  const fromType = ctx.typeChecker.getTypeOfSymbol(fromSym);
  const toType = ctx.typeChecker.getTypeOfSymbol(toSym);
  if (!ctx.isAssignableTo(fromType, toType)) {
    ctx.reportError(
      reportNode,
      `Cannot map field '${targetLabel}': type '${ctx.typeChecker.typeToString(fromType)}' of source field '${sourceLabel}' is not assignable to target type '${ctx.typeChecker.typeToString(toType)}'.`
    );
    return false;
  }
  return true;
}

/**
 * Report an error for an optional/nullable source object mapped into a
 * required, non-nullable target object.
 */
function checkNullability(
  ctx: MacroContext,
  reportNode: ts.Node,
  targetLabel: string,
  sourceLabel: string,
  fromNullable: boolean,
  toNullable: boolean
): void {
  if (fromNullable && !toNullable) {
    ctx.reportError(
      reportNode,
      `Cannot map field '${targetLabel}': source field '${sourceLabel}' may be null or undefined but the target field is required.`
    );
  }
}

/** `access == null ? access : whenPresent` */
function guardNullish(
  ctx: MacroContext,
  access: ts.Expression,
  whenPresent: ts.Expression
): ts.Expression {
  const f = ctx.factory;
  return f.createConditionalExpression(
    f.createBinaryExpression(access, ts.SyntaxKind.EqualsEqualsToken, f.createNull()),
    f.createToken(ts.SyntaxKind.QuestionToken),
    access,
    f.createToken(ts.SyntaxKind.ColonToken),
    whenPresent
  );
}

/**
 * Build the core object literal for a mapping.
 *
 * `prefix` is the dotted path of this object inside the top-level target,
 * used only in diagnostics.
 */
function buildObjectLiteral(
  ctx: MacroContext,
  callExpr: ts.CallExpression,
  sourceIdent: ts.Expression,
  fromType: ts.Type,
  toType: ts.Type,
  config: ParsedConfig,
  prefix: string
): ts.ObjectLiteralExpression {
  const fromProps = ctx.getPropertiesOfType(fromType);
  const toProps = ctx.getPropertiesOfType(toType);
  const fromByName = new Map(fromProps.map((p) => [p.name, p] as const));
  const toPropNames = new Set(toProps.map((p) => p.name));
  const resultProperties: ts.ObjectLiteralElementLike[] = [];
  const f = ctx.factory;

  // Every renamePaths target must name a real target field.
  for (const targetPath of config.renamePaths.keys()) {
    const head = targetPath.split(".")[0];
    if (!toPropNames.has(head)) {
      ctx.reportError(
        callExpr,
        `renamePaths: target path '${label(prefix, targetPath)}' does not exist in the target type.`
      );
    }
  }

  for (const toProp of toProps) {
    const name = toProp.name;
    const targetLabel = label(prefix, name);

    // Skip ignored target fields
    if (config.ignoreTarget.has(name)) {
      continue;
    }

    // Is it a constant?
    if (config.const.has(name)) {
      resultProperties.push(
        f.createPropertyAssignment(createPropName(ctx, name), config.const.get(name)!)
      );
      continue;
    }

    // Is it computed?
    if (config.compute.has(name)) {
      const computeLambda = config.compute.get(name)!;
      const inlineCall = f.createCallExpression(
        f.createParenthesizedExpression(computeLambda),
        undefined,
        [sourceIdent]
      );
      resultProperties.push(f.createPropertyAssignment(createPropName(ctx, name), inlineCall));
      continue;
    }

    const sourceName = config.rename.get(name) ?? name;
    const fromSym = fromByName.get(sourceName);
    const sourceLabel = label(prefix, sourceName);

    // Is it a collection field with sub-config?
    if (config.collections.has(name)) {
      const subConfig = parseConfig(ctx, config.collections.get(name)!, "collections");

      if (!fromSym) {
        ctx.reportError(
          callExpr,
          `Cannot map collection field '${targetLabel}': No matching field '${sourceName}' in source type.`
        );
        continue;
      }

      const sourceArrayAccess = createPropertyAccess(ctx, sourceIdent, sourceName);
      const from = fieldType(ctx, fromSym);
      const to = fieldType(ctx, toProp);
      const fromElemType = getArrayElementType(ctx, from.type);
      const toElemType = getArrayElementType(ctx, to.type);

      if (fromElemType && toElemType) {
        checkNullability(ctx, callExpr, targetLabel, sourceLabel, from.nullable, to.nullable);
        const itemParam = ctx.generateUniqueName("item");
        const elementMapping = buildObjectLiteral(
          ctx,
          callExpr,
          itemParam,
          fromElemType,
          toElemType,
          subConfig,
          `${targetLabel}[]`
        );
        const mapCall = f.createCallExpression(
          f.createPropertyAccessExpression(sourceArrayAccess, "map"),
          undefined,
          [createArrow(ctx, itemParam, elementMapping)]
        );
        resultProperties.push(
          f.createPropertyAssignment(
            createPropName(ctx, name),
            from.nullable ? guardNullish(ctx, sourceArrayAccess, mapCall) : mapCall
          )
        );
        continue;
      }

      // Fallback: just copy the array (only when it is actually compatible)
      checkFieldAssignable(ctx, callExpr, targetLabel, sourceLabel, fromSym, toProp);
      resultProperties.push(
        f.createPropertyAssignment(createPropName(ctx, name), sourceArrayAccess)
      );
      continue;
    }

    // Is it a nested object field with sub-config?
    if (config.nested.has(name)) {
      const subConfig = parseConfig(ctx, config.nested.get(name)!, "nested");

      if (!fromSym) {
        ctx.reportError(
          callExpr,
          `Cannot map nested field '${targetLabel}': No matching field '${sourceName}' in source type.`
        );
        continue;
      }

      const sourceFieldAccess = createPropertyAccess(ctx, sourceIdent, sourceName);
      // Strip null/undefined before reading properties: the properties of
      // `T | undefined` are empty, which used to map an optional nested
      // object to `{}` (FMG-6).
      const from = fieldType(ctx, fromSym);
      const to = fieldType(ctx, toProp);
      checkNullability(ctx, callExpr, targetLabel, sourceLabel, from.nullable, to.nullable);

      if (
        ctx.getPropertiesOfType(to.type).length > 0 &&
        ctx.getPropertiesOfType(from.type).length === 0
      ) {
        ctx.reportError(
          callExpr,
          `Cannot map nested field '${targetLabel}': the source type '${ctx.typeChecker.typeToString(from.type)}' of '${sourceLabel}' has no properties the macro can read.`
        );
        continue;
      }

      const nestedObjLit = buildObjectLiteral(
        ctx,
        callExpr,
        sourceFieldAccess,
        from.type,
        to.type,
        subConfig,
        targetLabel
      );
      resultProperties.push(
        f.createPropertyAssignment(
          createPropName(ctx, name),
          from.nullable ? guardNullish(ctx, sourceFieldAccess, nestedObjLit) : nestedObjLit
        )
      );
      continue;
    }

    // Dot-notation renamePaths below this field ("address.location": ...)
    const renamePathEntries = getRenamePaths(config, name);
    if (renamePathEntries.length > 0) {
      const childFrom = fromByName.get(name);
      const nestedExpr = buildRenamePathsLevel(
        ctx,
        callExpr,
        sourceIdent,
        fromType,
        childFrom ? createPropertyAccess(ctx, sourceIdent, name) : undefined,
        childFrom ? fieldType(ctx, childFrom).type : undefined,
        fieldType(ctx, toProp).type,
        renamePathEntries,
        targetLabel
      );
      resultProperties.push(f.createPropertyAssignment(createPropName(ctx, name), nestedExpr));
      continue;
    }

    // Top-level renamePaths (no dot in target path): "name": "a.b.c"
    if (config.renamePaths.has(name)) {
      const sourcePath = config.renamePaths.get(name)!.split(".");
      const resolved = resolveSourcePath(ctx, callExpr, sourceIdent, fromType, sourcePath, prefix);
      if (resolved) {
        checkFieldAssignable(
          ctx,
          callExpr,
          targetLabel,
          label(prefix, sourcePath.join(".")),
          resolved.symbol,
          toProp
        );
        resultProperties.push(
          f.createPropertyAssignment(createPropName(ctx, name), resolved.access)
        );
      }
      continue;
    }

    // Find in source
    if (fromSym) {
      checkFieldAssignable(ctx, callExpr, targetLabel, sourceLabel, fromSym, toProp);
      const propAccess = createPropertyAccess(ctx, sourceIdent, sourceName);
      resultProperties.push(f.createPropertyAssignment(createPropName(ctx, name), propAccess));
      continue;
    }

    // Missing mapping
    ctx.reportError(
      callExpr,
      `Cannot map field '${targetLabel}': No matching field '${sourceName}' in source type and no constant/compute rule provided.`
    );
  }

  return f.createObjectLiteralExpression(resultProperties, true);
}

/**
 * Get renamePaths entries that target a specific top-level field (dot-notation paths).
 * For "address.location": "address.city", returns entries for top-level field "address".
 */
function getRenamePaths(config: ParsedConfig, topLevelField: string): RenamePathEntry[] {
  const entries: RenamePathEntry[] = [];
  for (const [targetPath, sourcePath] of config.renamePaths) {
    const targetParts = targetPath.split(".");
    if (targetParts.length > 1 && targetParts[0] === topLevelField) {
      entries.push({
        targetSubPath: targetParts.slice(1),
        sourcePath: sourcePath.split("."),
      });
    }
  }
  return entries;
}

interface RenamePathEntry {
  /** Target path relative to the object being built. */
  targetSubPath: string[];
  /** Source path relative to the ROOT source. */
  sourcePath: string[];
}

/**
 * Walk a dotted source path from the root source, reporting a missing segment.
 */
function resolveSourcePath(
  ctx: MacroContext,
  reportNode: ts.Node,
  rootSource: ts.Expression,
  rootFromType: ts.Type,
  path: string[],
  prefix: string
): { access: ts.Expression; symbol: ts.Symbol } | undefined {
  let access: ts.Expression = rootSource;
  let type: ts.Type | undefined = rootFromType;
  let symbol: ts.Symbol | undefined;
  for (let i = 0; i < path.length; i++) {
    const part = path[i];
    symbol = type ? ctx.typeChecker.getPropertyOfType(type, part) : undefined;
    if (!symbol) {
      ctx.reportError(
        reportNode,
        `renamePaths: source path '${label(prefix, path.join("."))}' does not exist in the source type (no field '${part}').`
      );
      return undefined;
    }
    access = createPropertyAccess(ctx, access, part);
    type = fieldType(ctx, symbol).type;
  }
  return symbol ? { access, symbol } : undefined;
}

/**
 * Build one nested object level for dot-notation renamePaths (FMG-12): entries
 * of length 1 are renamed here, longer ones recurse one level deeper, and the
 * remaining target fields are copied from the same-named source field — or
 * reported when there is none and the target field is required.
 */
function buildRenamePathsLevel(
  ctx: MacroContext,
  callExpr: ts.CallExpression,
  rootSource: ts.Expression,
  rootFromType: ts.Type,
  levelSource: ts.Expression | undefined,
  levelFromType: ts.Type | undefined,
  levelToType: ts.Type,
  entries: RenamePathEntry[],
  prefix: string
): ts.Expression {
  const f = ctx.factory;
  const toProps = ctx.getPropertiesOfType(levelToType);
  const toPropNames = new Set(toProps.map((p) => p.name));
  const fromByName = new Map(
    (levelFromType ? ctx.getPropertiesOfType(levelFromType) : []).map((p) => [p.name, p] as const)
  );

  for (const entry of entries) {
    if (!toPropNames.has(entry.targetSubPath[0])) {
      ctx.reportError(
        callExpr,
        `renamePaths: target path '${prefix}.${entry.targetSubPath.join(".")}' does not exist in the target type.`
      );
    }
  }

  const properties: ts.ObjectLiteralElementLike[] = [];
  for (const toProp of toProps) {
    const name = toProp.name;
    const targetLabel = `${prefix}.${name}`;
    const here = entries.filter((e) => e.targetSubPath[0] === name);
    const exact = here.find((e) => e.targetSubPath.length === 1);
    const deeper = here.filter((e) => e.targetSubPath.length > 1);

    if (exact && deeper.length > 0) {
      ctx.reportError(
        callExpr,
        `renamePaths: '${targetLabel}' is renamed as a whole and also has renames below it.`
      );
      continue;
    }

    if (exact) {
      const resolved = resolveSourcePath(
        ctx,
        callExpr,
        rootSource,
        rootFromType,
        exact.sourcePath,
        ""
      );
      if (resolved) {
        checkFieldAssignable(
          ctx,
          callExpr,
          targetLabel,
          exact.sourcePath.join("."),
          resolved.symbol,
          toProp
        );
        properties.push(f.createPropertyAssignment(createPropName(ctx, name), resolved.access));
      }
      continue;
    }

    const fromSym = fromByName.get(name);

    if (deeper.length > 0) {
      const sub = buildRenamePathsLevel(
        ctx,
        callExpr,
        rootSource,
        rootFromType,
        fromSym && levelSource ? createPropertyAccess(ctx, levelSource, name) : undefined,
        fromSym ? fieldType(ctx, fromSym).type : undefined,
        fieldType(ctx, toProp).type,
        deeper.map((e) => ({ targetSubPath: e.targetSubPath.slice(1), sourcePath: e.sourcePath })),
        targetLabel
      );
      properties.push(f.createPropertyAssignment(createPropName(ctx, name), sub));
      continue;
    }

    if (fromSym && levelSource) {
      checkFieldAssignable(ctx, callExpr, targetLabel, targetLabel, fromSym, toProp);
      properties.push(
        f.createPropertyAssignment(
          createPropName(ctx, name),
          createPropertyAccess(ctx, levelSource, name)
        )
      );
      continue;
    }

    if (!isOptionalSymbol(toProp)) {
      ctx.reportError(
        callExpr,
        `Cannot map field '${targetLabel}': No matching field in source type and no renamePaths rule provided.`
      );
    }
  }

  return f.createObjectLiteralExpression(properties, true);
}

/**
 * Create a safe property access expression.
 */
function createPropertyAccess(ctx: MacroContext, expr: ts.Expression, name: string): ts.Expression {
  return isIdentifierName(name)
    ? ctx.factory.createPropertyAccessExpression(expr, name)
    : ctx.factory.createElementAccessExpression(expr, ctx.factory.createStringLiteral(name));
}

function isIdentifierName(name: string): boolean {
  return /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(name);
}

/**
 * Create a property name node.
 */
function createPropName(ctx: MacroContext, name: string): ts.Identifier | ts.StringLiteral {
  return isIdentifierName(name)
    ? ctx.factory.createIdentifier(name)
    : ctx.factory.createStringLiteral(name);
}

/**
 * Extract the element type from an array type.
 */
function getArrayElementType(ctx: MacroContext, type: ts.Type): ts.Type | undefined {
  // Check for number index type (arrays have numeric indexer)
  const numberIndexType = type.getNumberIndexType();
  if (numberIndexType) return numberIndexType;

  // Try type arguments if it's a generic Array<T>
  if ((type as ts.TypeReference).typeArguments?.length) {
    return (type as ts.TypeReference).typeArguments![0];
  }

  return undefined;
}

function isSimpleLiteral(expr: ts.Expression): boolean {
  return (
    ts.isStringLiteral(expr) ||
    ts.isNumericLiteral(expr) ||
    expr.kind === ts.SyntaxKind.TrueKeyword ||
    expr.kind === ts.SyntaxKind.FalseKeyword ||
    expr.kind === ts.SyntaxKind.NullKeyword
  );
}

interface ParsedConfig {
  rename: Map<string, string>;
  compute: Map<string, ts.Expression>;
  const: Map<string, ts.Expression>;
  ignoreTarget: Set<string>;
  ignoreSource: Set<string>;
  nested: Map<string, ts.Expression>;
  collections: Map<string, ts.Expression>;
  renamePaths: Map<string, string>;
}

/** Strip `(x)`, `x as T`, `x satisfies T` and `<T>x` wrappers. */
function unwrap(expr: ts.Expression): ts.Expression {
  let e = expr;
  while (
    ts.isParenthesizedExpression(e) ||
    ts.isAsExpression(e) ||
    ts.isSatisfiesExpression(e) ||
    ts.isTypeAssertionExpression(e)
  ) {
    e = e.expression;
  }
  return e;
}

function staticPropName(name: ts.PropertyName): string | undefined {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isNumericLiteral(name)) {
    return name.text;
  }
  if (ts.isNoSubstitutionTemplateLiteral(name)) return name.text;
  return undefined;
}

function stringValue(expr: ts.Expression): string | undefined {
  const e = unwrap(expr);
  if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) return e.text;
  return undefined;
}

const CONFIG_KEYS = new Set([
  "rename",
  "compute",
  "const",
  "ignore",
  "nested",
  "collections",
  "renamePaths",
]);

/**
 * Read a TransformConfig literal at compile time. Anything the macro cannot
 * read statically is reported (FMG-7) — silently dropping it used to make the
 * macro copy a same-named field instead of applying the rule.
 */
function parseConfig(
  ctx: MacroContext,
  rawConfigExpr: ts.Expression | undefined,
  where: string
): ParsedConfig {
  const config: ParsedConfig = {
    rename: new Map<string, string>(),
    compute: new Map<string, ts.Expression>(),
    const: new Map<string, ts.Expression>(),
    ignoreTarget: new Set<string>(),
    ignoreSource: new Set<string>(),
    nested: new Map<string, ts.Expression>(),
    collections: new Map<string, ts.Expression>(),
    renamePaths: new Map<string, string>(),
  };

  if (!rawConfigExpr) return config;
  const configExpr = unwrap(rawConfigExpr);
  if (ts.isIdentifier(configExpr) && configExpr.text === "undefined") return config;

  const err = (node: ts.Node, message: string) =>
    ctx.reportError(node, `${where} config: ${message}`);

  if (!ts.isObjectLiteralExpression(configExpr)) {
    err(
      rawConfigExpr,
      "must be an inline object literal — the macro reads it at compile time and cannot see the value of a variable or other expression."
    );
    return config;
  }

  /** Each member of a `{ target: value }` section, or undefined after reporting. */
  const sectionMembers = (
    key: string,
    init: ts.Expression
  ): readonly ts.ObjectLiteralElementLike[] | undefined => {
    const lit = unwrap(init);
    if (!ts.isObjectLiteralExpression(lit)) {
      err(init, `'${key}' must be an inline object literal.`);
      return undefined;
    }
    return lit.properties;
  };

  const memberName = (key: string, member: ts.ObjectLiteralElementLike): string | undefined => {
    if (ts.isSpreadAssignment(member)) {
      err(member, `spread ('...') is not supported in '${key}'; list each entry inline.`);
      return undefined;
    }
    const n = member.name ? staticPropName(member.name) : undefined;
    if (n === undefined) err(member, `'${key}' entries need a static (non-computed) name.`);
    return n;
  };

  for (const prop of configExpr.properties) {
    if (ts.isSpreadAssignment(prop)) {
      err(prop, "spread ('...') is not supported; write the config inline.");
      continue;
    }
    const key = prop.name ? staticPropName(prop.name) : undefined;
    if (key === undefined || !CONFIG_KEYS.has(key)) {
      err(
        prop,
        key === undefined
          ? "computed keys are not supported."
          : `unknown option '${key}' (expected one of: ${[...CONFIG_KEYS].join(", ")}).`
      );
      continue;
    }
    if (!ts.isPropertyAssignment(prop)) {
      err(prop, `'${key}' must be written as '${key}: { ... }'.`);
      continue;
    }

    if (key === "ignore") {
      const members = sectionMembers(key, prop.initializer);
      for (const sub of members ?? []) {
        const subKey = memberName(key, sub);
        if (subKey === undefined) continue;
        if ((subKey !== "source" && subKey !== "target") || !ts.isPropertyAssignment(sub)) {
          err(sub, `'ignore' accepts only 'source: [...]' and 'target: [...]'.`);
          continue;
        }
        const arr = unwrap(sub.initializer);
        if (!ts.isArrayLiteralExpression(arr)) {
          err(sub, `'ignore.${subKey}' must be an inline array of field names.`);
          continue;
        }
        const set = subKey === "target" ? config.ignoreTarget : config.ignoreSource;
        for (const elem of arr.elements) {
          const v = stringValue(elem);
          if (v === undefined) err(elem, `'ignore.${subKey}' entries must be string literals.`);
          else set.add(v);
        }
      }
      continue;
    }

    const members = sectionMembers(key, prop.initializer);
    for (const sub of members ?? []) {
      const targetKey = memberName(key, sub);
      if (targetKey === undefined) continue;

      if (key === "compute") {
        if (ts.isPropertyAssignment(sub)) {
          config.compute.set(targetKey, sub.initializer);
        } else if (ts.isShorthandPropertyAssignment(sub)) {
          config.compute.set(targetKey, sub.name);
        } else if (ts.isMethodDeclaration(sub) && sub.body) {
          // `label(x) { ... }` → `function (x) { ... }`
          config.compute.set(
            targetKey,
            ctx.factory.createFunctionExpression(
              sub.modifiers?.filter(
                (m): m is ts.ModifierToken<ts.SyntaxKind.AsyncKeyword> =>
                  m.kind === ts.SyntaxKind.AsyncKeyword
              ),
              sub.asteriskToken,
              undefined,
              sub.typeParameters,
              sub.parameters,
              sub.type,
              sub.body
            )
          );
        } else {
          err(sub, `unsupported 'compute' entry for '${targetKey}'.`);
        }
        continue;
      }

      if (key === "const") {
        if (ts.isPropertyAssignment(sub)) config.const.set(targetKey, sub.initializer);
        else if (ts.isShorthandPropertyAssignment(sub)) config.const.set(targetKey, sub.name);
        else err(sub, `unsupported 'const' entry for '${targetKey}'.`);
        continue;
      }

      if (!ts.isPropertyAssignment(sub)) {
        err(sub, `'${key}.${targetKey}' must be written as '${targetKey}: ...'.`);
        continue;
      }

      if (key === "rename" || key === "renamePaths") {
        const v = stringValue(sub.initializer);
        if (v === undefined) {
          err(
            sub.initializer,
            `'${key}.${targetKey}' must be a string literal naming the source ${key === "rename" ? "field" : "path"}.`
          );
          continue;
        }
        (key === "rename" ? config.rename : config.renamePaths).set(targetKey, v);
      } else if (key === "nested") {
        config.nested.set(targetKey, sub.initializer);
      } else if (key === "collections") {
        config.collections.set(targetKey, sub.initializer);
      }
    }
  }

  return config;
}

